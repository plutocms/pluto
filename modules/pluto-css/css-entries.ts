// Pure helpers for the pluto-css module. They do not import `nuxt/kit`, so
// the unit tests can call them directly.
import { dirname, isAbsolute, join, relative, resolve } from 'node:path'

/** A layer's own CSS file, by convention. See the single-tailwind-build skill. */
export const LAYER_CSS_FILE = 'assets/css/pluto-layer.css'

function toPosix(path: string): string {
  return path.replaceAll('\\', '/')
}

/**
 * Returns the `pluto-layer.css` file of every layer that has one, base
 * layer first. Nuxt lists the layers top first (the app, then each layer it
 * extends), so the list is reversed: a higher layer's `@theme` then comes
 * later in the build and wins.
 */
export function findLayerCssFiles(
  layerAppDirs: string[],
  exists: (path: string) => boolean
): string[] {
  return [...layerAppDirs]
    .reverse()
    .map((appDir) => toPosix(join(appDir, LAYER_CSS_FILE)))
    .filter((file) => exists(file))
}

/**
 * Renders `#build/pluto.css`: one `@import` for each layer CSS file. Each
 * path is relative to the build dir, where the file is written. A path on
 * another drive (Windows) stays absolute.
 */
export function renderPlutoCss(files: string[], buildDir: string): string {
  return [
    '/* Generated by @plutocms/pluto (modules/pluto-css). Do not edit. */',
    "/* Each Pluto layer's app/assets/css/pluto-layer.css, base layer first. */",
    ...files.map((file) => cssImport(file, buildDir)),
    '',
  ].join('\n')
}

/**
 * Renders `#build/pluto-site.css`: the opt-in Pluto site theme of core
 * (app/assets/css/pluto-site-theme.css). An app imports it after `#build/pluto.css`.
 */
export function renderPlutoSiteCss(file: string, buildDir: string): string {
  return [
    '/* Generated by @plutocms/pluto (modules/pluto-css). Do not edit. */',
    '/* The Pluto site theme: opt-in, for a public site. */',
    cssImport(file, buildDir),
    '',
  ].join('\n')
}

/** An `@import` of `file`, relative to the build dir. A path on another drive (Windows) stays absolute. */
function cssImport(file: string, buildDir: string): string {
  const fromBuild = toPosix(relative(buildDir, file))
  const path = isAbsolute(fromBuild)
    ? fromBuild
    : fromBuild.startsWith('.')
      ? fromBuild
      : `./${fromBuild}`
  return `@import "${path}";`
}

/** The fallback entry, used only when the app has no Tailwind entry. */
export function renderPlutoEntryCss(): string {
  return [
    '/* Generated by @plutocms/pluto (modules/pluto-css). Do not edit. */',
    '/* Fallback Tailwind entry: the app has no CSS entry that imports Tailwind. */',
    '@import "tailwindcss";',
    '@import "@nuxt/ui";',
    '@import "#build/pluto.css";',
    '',
  ].join('\n')
}

/** Removes CSS comments. */
function stripComments(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, '')
}

/**
 * Returns the specifier of every `@import` in a CSS text: `@import 'x'`,
 * `@import "x" source(none)`, `@import url(x)`, and `@import url('x')`.
 */
export function parseCssImports(css: string): string[] {
  const imports: string[] = []
  // Two simple steps keep both patterns linear: take the body of each
  // `@import ...;`, then read the specifier at its start.
  for (const statement of stripComments(css).matchAll(/@import\s([^;]*);/g)) {
    const body = statement[1]!.trim().replace(/^url\(\s*/, '')
    const specifier =
      /^(['"])(.*?)\1/.exec(body)?.[2] ?? /^[^\s)]+/.exec(body)?.[0]
    if (specifier) {
      imports.push(specifier)
    }
  }
  return imports
}

export interface CssEntryInfo {
  /** The CSS entry, as resolved to a file. */
  file: string
  /** It imports Tailwind (`@import 'tailwindcss'`), so it is a Tailwind build. */
  tailwind: boolean
  /** It imports `@nuxt/ui`. */
  nuxtUi: boolean
  /** It imports `#build/pluto.css`. */
  plutoCss: boolean
}

/**
 * Follows the local `@import`s of a CSS entry, to `maxDepth`, and reports
 * what it imports. `resolveImport` turns a specifier into a file path, or
 * returns `undefined` for a package import (such as `tailwindcss`), which is
 * not followed.
 */
export function analyzeCssEntry(
  file: string,
  read: (path: string) => string | undefined,
  resolveImport: (specifier: string, fromFile: string) => string | undefined,
  maxDepth = 3
): CssEntryInfo {
  const info: CssEntryInfo = {
    file,
    tailwind: false,
    nuxtUi: false,
    plutoCss: false,
  }
  const seen = new Set<string>()

  function visit(path: string, depth: number) {
    if (seen.has(path) || depth > maxDepth) {
      return
    }
    seen.add(path)
    const css = read(path)
    if (css === undefined) {
      return
    }
    for (const specifier of parseCssImports(css)) {
      if (specifier === 'tailwindcss') {
        info.tailwind = true
      } else if (specifier === '@nuxt/ui') {
        info.nuxtUi = true
      } else if (
        /(?:^|\/)pluto\.css$/.test(specifier) &&
        specifier.includes('#build')
      ) {
        info.plutoCss = true
      } else {
        const next = resolveImport(specifier, path)
        if (next) {
          visit(next, depth + 1)
        }
      }
    }
  }

  visit(file, 0)
  return info
}

/** Resolves a relative `@import` (`./x.css`, `../x.css`) against its file. */
export function resolveRelativeImport(
  specifier: string,
  fromFile: string
): string | undefined {
  return specifier.startsWith('./') || specifier.startsWith('../')
    ? toPosix(resolve(dirname(fromFile), specifier))
    : undefined
}

export interface CssSetupReport {
  /** Inject the fallback entry: no CSS entry imports Tailwind. */
  injectFallback: boolean
  warnings: string[]
}

/**
 * Checks the app's CSS setup against the single-build rules and returns
 * what to do. `layerRoots` are the root dirs of every layer except the app.
 */
export function checkCssSetup(
  entries: CssEntryInfo[],
  layerRoots: string[]
): CssSetupReport {
  const warnings: string[] = []
  const tailwindEntries = entries.filter((entry) => entry.tailwind)
  const snippet =
    "  @import 'tailwindcss';\n  @import '@nuxt/ui';\n  @import '#build/pluto.css';"

  if (tailwindEntries.length === 0) {
    return { injectFallback: true, warnings }
  }

  for (const entry of tailwindEntries) {
    const layerRoot = layerRoots.find((root) =>
      toPosix(entry.file).startsWith(toPosix(root))
    )
    if (layerRoot) {
      warnings.push(
        `Layer ${layerRoot} registers its own Tailwind build (${entry.file}). Remove it from the layer's \`css\` option, and move its tokens to app/${LAYER_CSS_FILE}.`
      )
    }
  }

  if (tailwindEntries.length > 1) {
    warnings.push(
      `Found ${tailwindEntries.length} Tailwind builds. Keep one, in the app. Builds:\n${tailwindEntries.map((entry) => `  - ${entry.file}`).join('\n')}`
    )
  }

  if (!tailwindEntries.some((entry) => entry.plutoCss)) {
    warnings.push(
      `No CSS entry imports #build/pluto.css. The admin theme and layer tokens are missing. Start the app's CSS entry with:\n${snippet}`
    )
  }

  if (!tailwindEntries.some((entry) => entry.nuxtUi)) {
    warnings.push(
      `No CSS entry imports @nuxt/ui. Nuxt UI styles, the \`light:\` variant, and the layer sources are missing. Start the app's CSS entry with:\n${snippet}`
    )
  }

  return { injectFallback: false, warnings }
}
