export const LOCALE_DIR = 'i18n/locales'

const LOCALE_CODE = /^[a-z]{2,3}(?:-[A-Z]{2})?$/

export function isLocaleCode(value: string): boolean {
  return LOCALE_CODE.test(value)
}

function toPosix(path: string): string {
  return path.replaceAll('\\', '/')
}

export function findLayerLocaleFiles(
  layerRoots: string[],
  listDir: (dir: string) => string[]
): Record<string, string[]> {
  const files: Record<string, string[]> = {}
  for (const root of [...layerRoots].reverse()) {
    const dir = join(root, LOCALE_DIR)
    for (const name of listDir(dir).toSorted()) {
      if (!name.endsWith('.json')) {
        continue
      }
      const code = name.slice(0, -'.json'.length)
      if (isLocaleCode(code)) {
        ;(files[code] ??= []).push(toPosix(join(dir, name)))
      }
    }
  }
  return files
}

export function resolveNuxtUiLocaleFile(
  code: string,
  available: string[]
): string {
  const full = code.toLowerCase().replaceAll('-', '_')
  if (available.includes(full)) {
    return full
  }
  const base = full.split('_')[0]!
  if (available.includes(base)) {
    return base
  }
  return 'en'
}

export interface I18nTemplateInput {
  files: Record<string, string[]>
  defaultLocale: string
  uiLocaleDir: string
  uiLocaleFiles: string[]
}

const MERGE_SOURCE = [
  'function isTree(value) {',
  "  return typeof value === 'object' && value !== null",
  '}',
  '',
  'function merge(...trees) {',
  '  const result = {}',
  '  for (const tree of trees) {',
  '    for (const [key, value] of Object.entries(tree)) {',
  '      result[key] = isTree(value) ? merge(isTree(result[key]) ? result[key] : {}, value) : value',
  '    }',
  '  }',
  '  return result',
  '}',
]

function renderMessageLoaders(
  files: Record<string, string[]>,
  codes: string[]
): string[] {
  return codes.map((code) => {
    const imports = files[code]!.map(
      (file) => `import(${JSON.stringify(file)})`
    ).join(', ')
    return `  ${JSON.stringify(code)}: async () => merge(...(await Promise.all([${imports}])).map((m) => m.default ?? m)),`
  })
}

export interface ServerI18nTemplateInput {
  files: Record<string, string[]>
  defaultLocale: string
}

export function renderServerI18nModule(input: ServerI18nTemplateInput): string {
  const codes = Object.keys(input.files).toSorted()
  return [
    '// Generated by @plutocms/core (modules/pluto-i18n). Do not edit.',
    `export const localeCodes = ${JSON.stringify(codes)}`,
    `export const defaultLocale = ${JSON.stringify(input.defaultLocale)}`,
    '',
    ...MERGE_SOURCE,
    '',
    'export const messageLoaders = {',
    ...renderMessageLoaders(input.files, codes),
    '}',
    '',
  ].join('\n')
}

export function renderI18nTemplate(input: I18nTemplateInput): string {
  const codes = Object.keys(input.files).toSorted()
  const messageLoaders = renderMessageLoaders(input.files, codes)
  const uiLocaleLoaders = codes.map((code) => {
    const file = resolveNuxtUiLocaleFile(code, input.uiLocaleFiles)
    const path = `${toPosix(input.uiLocaleDir).replace(/\/$/, '')}/${file}.js`
    return `  ${JSON.stringify(code)}: () => import(${JSON.stringify(path)}).then((m) => m.default),`
  })
  return [
    '// Generated by @plutocms/core (modules/pluto-i18n). Do not edit.',
    "// Each layer's i18n/locales/<code>.json, base layer first, the app last.",
    `export const localeCodes = ${JSON.stringify(codes)}`,
    `export const defaultLocale = ${JSON.stringify(input.defaultLocale)}`,
    '',
    ...MERGE_SOURCE,
    '',
    'export const messageLoaders = {',
    ...messageLoaders,
    '}',
    '',
    'export const uiLocaleLoaders = {',
    ...uiLocaleLoaders,
    '}',
    '',
  ].join('\n')
}

export function renderI18nTypes(): string {
  return [
    '// Generated by @plutocms/core (modules/pluto-i18n). Do not edit.',
    'export declare const localeCodes: string[]',
    'export declare const defaultLocale: string',
    'export declare const messageLoaders: Record<string, () => Promise<Record<string, unknown>>>',
    'export declare const uiLocaleLoaders: Record<string, () => Promise<any>>',
    '',
  ].join('\n')
}

const PLACEHOLDER = /\{(\w+)\}/g

export function messagePlaceholders(message: string): string[] {
  const names = new Set<string>()
  for (const match of message.matchAll(PLACEHOLDER)) {
    names.add(match[1]!)
  }
  if (message.includes(' | ')) {
    names.add('count')
  }
  return [...names].toSorted()
}

export function renderMessageTypes(trees: MessageTree[]): string {
  const flat = flattenMessages(mergeMessageTrees(...trees))
  const lines = Object.keys(flat)
    .toSorted()
    .map((key) => {
      const names = messagePlaceholders(flat[key]!)
      const value =
        names.length > 0
          ? names.map((name) => JSON.stringify(name)).join(' | ')
          : 'never'
      return `    ${JSON.stringify(key)}: ${value}`
    })

  return [
    '// Generated by @plutocms/core (modules/pluto-i18n). Do not edit.',
    'export {}',
    '',
    'declare global {',
    '  interface PlutoMessages {',
    ...lines,
    '  }',
    '}',
    '',
  ].join('\n')
}

/**
 * The options of the `plutoI18n` key of `nuxt.config.ts`.
 *
 * @see https://pluto.vulmix.dev/docs/build/i18n
 */
export interface PlutoI18nOptions {
  /** The fallback locale, and the last choice of every resolve order. Default `en`. */
  defaultLocale?: string
  /** Locales the admin offers. Default: every discovered locale. */
  adminLocales?: string[]
  /** Locales the public site can use. Default: every discovered locale. */
  siteLocales?: string[]
  /** The public site's locale. Default: `defaultLocale`. */
  siteLocale?: string
}

export interface ResolvedI18nOptions {
  defaultLocale: string
  adminLocales: string[]
  siteLocales: string[]
  siteLocale: string
  siteManaged: boolean
  warnings: string[]
}

export function resolveI18nOptions(
  options: PlutoI18nOptions,
  discovered: string[]
): ResolvedI18nOptions {
  const warnings: string[] = []
  const known = new Set(discovered)

  function pick(name: string, wanted: string[] | undefined): string[] {
    if (!wanted) {
      return [...discovered]
    }
    const kept = wanted.filter((code) => known.has(code))
    for (const code of wanted.filter((code) => !known.has(code))) {
      warnings.push(
        `plutoI18n.${name} lists "${code}", but no layer has i18n/locales/${code}.json. Dropped.`
      )
    }
    return kept
  }

  let defaultLocale = options.defaultLocale ?? 'en'
  if (!known.has(defaultLocale)) {
    warnings.push(
      `plutoI18n.defaultLocale "${defaultLocale}" has no locale file. Using "en".`
    )
    defaultLocale = 'en'
  }

  const adminLocales = pick('adminLocales', options.adminLocales)
  const siteLocales = pick('siteLocales', options.siteLocales)

  let siteLocale = options.siteLocale ?? defaultLocale
  if (!siteLocales.includes(siteLocale)) {
    warnings.push(
      `plutoI18n.siteLocale "${siteLocale}" is not in siteLocales. Using "${defaultLocale}".`
    )
    siteLocale = defaultLocale
  }

  const siteManaged =
    options.siteLocale !== undefined || options.siteLocales !== undefined

  return {
    defaultLocale,
    adminLocales,
    siteLocales,
    siteLocale,
    siteManaged,
    warnings,
  }
}
